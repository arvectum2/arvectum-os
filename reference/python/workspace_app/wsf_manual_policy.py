"""Exact local manual-context policy gate candidate.

Not installed in the application. Production composition must pin an approved
policy digest after a separate owner approval and effective contract publication.
No configuration is generated by this module and no grants are created here.
"""
from datetime import datetime, timedelta, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import stat

import p7_04_persistent_access as p704
from .wsf_manual_context import ManualContextError, ManualContextStore, _identity

RESOURCE = "manual-context"
OPERATIONS = frozenset({"workspace.context.project", "workspace.context.capture",
                        "workspace.context.revise", "workspace.context.read",
                        "workspace.context.export"})
POLICY_SCHEMA = "arvectum.workspace.manual-context-policy/1"
MAX_POLICY_BYTES = 8192


def _private_file(path):
    if path.resolve() != path:
        raise ManualContextError("policy path unsafe")
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
    with os.fdopen(fd, "rb") as f:
        s = os.fstat(f.fileno())
        if not stat.S_ISREG(s.st_mode) or s.st_uid != os.getuid() or s.st_mode & 0o077 or s.st_nlink != 1:
            raise ManualContextError("policy file unsafe")
        raw = f.read(MAX_POLICY_BYTES+1)
        if len(raw) > MAX_POLICY_BYTES:
            raise ManualContextError("policy too large")
        return raw


class ManualPolicyGate:
    def __init__(self, runtime_root, approved_policy_sha256, approved_draft_blob):
        self.root = Path(runtime_root)
        if not self.root.is_absolute() or self.root.resolve() != self.root:
            raise ManualContextError("unsafe runtime root")
        if not isinstance(approved_policy_sha256, str) or not re.fullmatch("[0-9a-f]{64}", approved_policy_sha256):
            raise ManualContextError("approved policy pin required")
        if not isinstance(approved_draft_blob, str) or not re.fullmatch("[0-9a-f]{40}", approved_draft_blob):
            raise ManualContextError("approved contract pin required")
        self.policy_sha = approved_policy_sha256
        self.draft_blob = approved_draft_blob

    def authorize(self, access, operation):
        if operation not in OPERATIONS:
            raise ManualContextError("operation unavailable")
        try:
            raw = _private_file(self.root / "config" / "manual-context-policy.json")
            if hashlib.sha256(raw).hexdigest() != self.policy_sha:
                raise ManualContextError("policy pin mismatch")
            policy = json.loads(raw)
            if (not isinstance(policy, dict) or set(policy) != {
                    "schema","contract_draft_blob","scope","credential_id","starts_at","expires_at","grants","purpose"}
                or policy["schema"] != POLICY_SCHEMA or policy["contract_draft_blob"] != self.draft_blob
                or policy["scope"] != _identity(access) or policy["credential_id"] != access.credential_id
                or policy["purpose"] != "restricted-internal-project-coordination"
                or not isinstance(policy["grants"],dict) or set(policy["grants"]) != OPERATIONS
                or any(not isinstance(x,str) or not re.fullmatch("[0-9a-f]{32}",x) for x in policy["grants"].values())
                or len(set(policy["grants"].values())) != len(OPERATIONS)):
                raise ManualContextError("policy binding mismatch")
            start,end = (datetime.fromisoformat(policy[k]) for k in ("starts_at","expires_at"))
            if (start.utcoffset() != timedelta(0) or end.utcoffset() != timedelta(0)
                or not start <= datetime.now(timezone.utc) < end or end-start > timedelta(days=30)):
                raise ManualContextError("pilot unavailable")
            if not re.fullmatch("[0-9a-f]{32}", access.credential_id):
                raise ManualContextError("credential identity invalid")
            decision = p704.authorize_from_credential_file(
                self.root, organization=access.organization, principal=access.actor,
                credential_id=access.credential_id,
                credential_file=self.root/"secrets"/"p7-04"/(access.credential_id+".secret"),
                operation=operation, resource=RESOURCE, access_path="local")
            if not decision.allowed or decision.principal_kind != "human" or decision.grant_id != policy["grants"][operation]:
                raise ManualContextError("operation grant unavailable")
            directory = self.root / "workspace-company-manual-context"
            if directory.resolve() != directory or not directory.is_dir() or not (directory/"context.json").is_file():
                raise ManualContextError("initialized primary store unavailable")
            # Do not initialize/recreate missing primary snapshots on a read.
            store = ManualContextStore(directory, access, require_initialized=True)
            with store._locked():
                if not store.path.is_file() or store.path.is_symlink():
                    raise ManualContextError("initialized primary snapshot missing")
                fd = store._open(store.path, os.O_RDONLY)
                with os.fdopen(fd, "rb") as f:
                    store._decode(f.read(2 * 1024 * 1024 + 1))
            return store
        except (OSError, ValueError, TypeError, KeyError, AttributeError, RecursionError, p704.P704Error) as exc:
            raise ManualContextError("manual context policy unavailable") from exc
